#!/usr/bin/env bash
# Rebuild sim-run/db/simdb_test_data.sql: QuantReplay demo data (Liquibase) + real-market reference data.
# Runs a throw-away database + Liquibase in a separate compose project, so the running stack is not touched.
# Use after changing sim-run/db/real_market_overrides.sql or after a simulator image upgrade.
set -euo pipefail
cd "$(dirname "$0")/../sim-run"

PROJECT=simdb-build
OUT=db/simdb_test_data.sql
COMPOSE=(docker compose -p "$PROJECT" -f - )

compose_file() {
  cat <<'YAML'
services:
  database:
    image: ghcr.io/quod-financial/postgres_marketsim:latest
    container_name: simdb-build-database
    tmpfs: [ /var/lib/postgresql/data ]
    environment: [ POSTGRES_DB=simdb, POSTGRES_USER=postgres, POSTGRES_PASSWORD=postgres ]
    healthcheck:
      test: [ "CMD-SHELL", "pg_isready -h 127.0.0.1 -U postgres -d simdb" ]
      retries: 30
      interval: 2s
  liquibase:
    image: ghcr.io/quod-financial/liquibase:latest
    environment: [ SIMULATOR_DATABASE_HOST=database ]
    depends_on:
      database:
        condition: service_healthy
YAML
}

cleanup() { compose_file | "${COMPOSE[@]}" down -v >/dev/null 2>&1 || true; }
trap cleanup EXIT

compose_file | "${COMPOSE[@]}" up -d database
compose_file | "${COMPOSE[@]}" run --rm liquibase >/dev/null        # demo schema + data
docker exec -i simdb-build-database psql -U postgres -d simdb -v ON_ERROR_STOP=1 -q < db/real_market_overrides.sql

{
  cat <<'HEADER'
-- QuantReplay simulator test database (schema `sim`): demo data + real-market reference data
-- from sim-run/db/real_market_overrides.sql. Generated by scripts/build_test_db.sh - do not edit by hand.
-- Loaded by the database container on first start (docker-entrypoint-initdb.d, after the image's init.sql
-- that creates the `sim` user and schema).
HEADER
  docker exec simdb-build-database pg_dump -U postgres -d simdb -n sim --no-comments \
    | sed -E '/^\\(un)?restrict /d; /^CREATE SCHEMA sim;$/d'
} > "$OUT"
echo "written $OUT"
